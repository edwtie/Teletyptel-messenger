<?php
declare(strict_types=1);
require_once dirname(__DIR__) . '/lib/TranslationXmppService.php';
require_once dirname(__DIR__) . '/lib/Xmpp/XmppAutoload.php';
$pdo = new PDO('sqlite::memory:', null, null, [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
$pdo->exec('CREATE TABLE account_profiles (account_id TEXT PRIMARY KEY, jid TEXT)');
$pdo->exec("INSERT INTO account_profiles VALUES ('alice', 'alice@example.test'), ('bob', 'bob@example.test')");
AccountAccess::ensureSchema($pdo);
$calls = [];
$translator = new TranslationService($pdo, ['enabled' => true, 'apiKey' => 'fixture'], function ($input) use (&$calls) {
    $calls[] = $input;
    return ['data' => ['translations' => [['translatedText' => 'Translation <safe> & ' . $input['target'], 'detectedSourceLanguage' => 'nl']]]];
});
$translator->ensureSchema();
$translator->savePreferences('alice', ['mode' => 'automatic', 'automaticConsent' => true, 'targetLanguage' => 'en', 'liveRttConsent' => true]);
$translator->savePreferences('bob', ['mode' => 'manual', 'targetLanguage' => 'tr']);
$service = new TranslationXmppService($pdo, $translator, 'translation@example.test/service');
$checks = 0;
$check = function ($valid, $label) use (&$checks) { if (!$valid) throw new RuntimeException($label); $checks++; };
$request = fn($from, $payload) => '<iq xmlns="jabber:client" from="' . $from . '" to="translation@example.test/service" type="get" id="test">' . $payload . '</iq>';
$payload = fn($target) => '<x xmlns="urn:xmpp:langtrans"><source xml:lang="nl">Hallo &amp; test</source><translation destination_lang="' . $target . '"/></x>';
$result = $service->handle($request('alice@example.test/phone', $payload('en')));
$check(str_contains($result, 'to="alice@example.test/phone"') && str_contains($result, 'type="result"'), 'Private reply to authenticated requester');
$check(str_contains($result, '&lt;safe&gt; &amp; en'), 'Translation is escaped XML');
$check(str_contains($result, 'source_lang="nl"'), 'XEP-0171 source metadata');
$result = $service->handle($request('bob@example.test/phone', $payload('tr')));
$check(str_contains($result, 'destination_lang="tr"'), 'Independent recipient target');
$check(array_column($calls, 'target') === ['en', 'tr'], 'No shared target between users');
$check(str_contains($service->handle($request('bob@example.test/phone', $payload('en'))), 'preferences_changed'), 'Cannot override saved target');
$check(str_contains($service->handle($request('stranger@example.test/phone', $payload('en'))), 'forbidden'), 'Unknown users denied');
$check($service->handle('<message xmlns="jabber:client" type="groupchat"><body>Do not translate</body></message>') === null, 'Never responds to group broadcasts');
$check($service->handle('<!DOCTYPE iq [<!ENTITY x SYSTEM "file:///secret">]><iq/>') === null, 'DTD rejected');
$check($service->handle('<iq xmlns="wrong" type="get"/>') === null, 'Namespace enforced');
$live = '<context xmlns="urn:teletyptel:translation:0" live="true" direction="peer"/>';
$check(str_contains($service->handle($request('alice@example.test/phone', $payload('en') . $live)), 'type="result"'), 'Incoming live permission allowed');
$check(str_contains($service->handle($request('bob@example.test/phone', $payload('tr') . $live)), 'consent_required'), 'Live permission required');
$own = '<context xmlns="urn:teletyptel:translation:0" live="true" direction="self"/>';
$check(str_contains($service->handle($request('alice@example.test/phone', $payload('en') . $own)), 'consent_required'), 'Own drafts require separate consent');
$disco = $service->handle($request('alice@example.test/phone', '<query xmlns="http://jabber.org/protocol/disco#info"/>'));
$check(str_contains($disco, 'urn:xmpp:langtrans'), 'Service discovery');
$items = $service->handle($request('alice@example.test/phone', '<query xmlns="urn:xmpp:langtrans:items"/>'));
$check(str_contains($items, 'source_lang="en" destination_lang="tr"'), 'Language discovery');
$pdo->exec("INSERT INTO account_access_controls VALUES ('alice',1,NULL,2,'2026-10-26')");
$before = count($calls);
$check(str_contains($service->handle($request('alice@example.test/phone', $payload('en'))), 'forbidden'), 'Blocked accounts denied');
$check(count($calls) === $before, 'Unauthorized requests never call Google');
$stream = new Tiedragon\Xmpp\XmppStreamClient(Tiedragon\Xmpp\XmppConnectionSettings::forAccount('fixture@example.test'));
$resource = fopen('php://temp', 'w+');
(new ReflectionProperty($stream, 'stream'))->setValue($stream, $resource);
$buffer = (new ReflectionProperty($stream, 'buffer'))->getValue($stream);
$buffer->append('<stream:stream xmlns="jabber:client" xmlns:stream="http://etherx.jabber.org/streams"><stream:features/><iq id="first" type="result"/><iq id="second" type="result"/>');
$first = $stream->nextStanza(1);
$second = $stream->nextStanza(1);
$check($first->id === 'first' && $second->id === 'second', 'Coalesced stream elements are not lost');
$check(str_contains($first->xml, 'xmlns="jabber:client"'), 'Inherited stream namespace restored on standalone stanzas');
$stream->close();
echo "XEP-0171 service smoke passed: {$checks} checks, no external calls.\n";
